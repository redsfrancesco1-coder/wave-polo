// GitHub Pages: reads a snapshot generated by GitHub Actions, not a live FIN API.
export async function getChampionship(id, view = 'squadre', round = 7, team = '') {
  const championship = championships.find(item => item.id === id);
  if (!championship) throw new Error('Campionato non riconosciuto');
  if (id !== 'a1-maschile-2026-27') return { ...championship, status: 'pending' };
  const response = await fetch('./data/fin-a1-maschile.json?t=' + Date.now(), { cache: 'no-store' });
  if (!response.ok) throw new Error('Dati FIN non ancora pubblicati su questo sito');
  const snapshot = await response.json();
  if (snapshot.status !== 'available' || snapshot.season !== championship.season) throw new Error('Dati FIN non validi');
  if (view === 'scheda') {
    const statistics = snapshot.standings.find(t => t.teamId === team);
    if (!statistics) throw new Error('Squadra non disponibile');
    const fixtures = snapshot.fixtures.filter(g => g.homeTeamId === team || g.awayTeamId === team);
    return { ...championship, ...snapshot, team: { id: team, name: statistics.name }, statistics,
      fixtures, results: fixtures.filter(g => g.status === 'disputata'), calendarStatus: 'available',
      calendarCheckedAt: snapshot.checkedAt };
  }
  return { ...championship, ...snapshot };
}
